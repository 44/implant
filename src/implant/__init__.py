#!/usr/bin/env python3
"""Implant - a wrapper around magic-wormhole/croc for secure file transfer."""

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


def wormhole_cmd():
    """Return command prefix for magic-wormhole, using uvx as fallback."""
    exe = shutil.which("wormhole")
    if exe:
        return [exe]
    return ["uvx", "--no-config", "magic-wormhole"]


def croc_cmd():
    """Return command prefix for croc, or None if not installed."""
    exe = shutil.which("croc")
    return [exe] if exe else None


def detect_transfer(preferred):
    """Pick a transfer backend. Explicit choice wins, else prefer native tools."""
    if preferred != "auto":
        return preferred
    if shutil.which("wormhole"):
        return "wormhole"
    if shutil.which("croc"):
        return "croc"
    if shutil.which("uvx"):
        return "wormhole"
    return None


def run(cmd, cwd=None):
    """Run a command, inheriting stdio, and exit on failure."""
    print("+ " + " ".join(cmd), flush=True)
    rc = subprocess.call(cmd, cwd=cwd)
    if rc != 0:
        print(f"Error: command failed with exit code {rc}", file=sys.stderr, flush=True)
        sys.exit(rc)


def find_install_script(tmpdir):
    """Locate install.py in the received payload."""
    received_items = [p for p in Path(tmpdir).iterdir() if p.name != ".croc"]
    if not received_items:
        return None, None

    received_path = received_items[0]
    install_script = (
        received_path / "install.py"
        if received_path.is_dir()
        else Path(tmpdir) / "install.py"
    )
    return received_path, install_script


def receive(transfer, code):
    """Receive a folder and execute install.py."""
    if transfer == "croc":
        cmd = croc_cmd()
        if cmd is None:
            print(
                "Error: croc is not installed (required for --croc)",
                file=sys.stderr,
                flush=True,
            )
            sys.exit(1)
        if not code:
            # croc has no "allocate code and wait" mode; sender must provide one.
            print(
                "Error: --code is required when receiving with croc "
                "(croc codes are generated by the sender)",
                file=sys.stderr,
                flush=True,
            )
            sys.exit(1)
    else:
        cmd = wormhole_cmd()

    print(f"Starting receiver ({transfer})...", flush=True)

    orig_dir = os.getcwd()
    with tempfile.TemporaryDirectory() as tmpdir:
        try:
            if transfer == "wormhole":
                receive_cmd = cmd + ["receive", "--no-listen", "--accept-file"]
                if code:
                    receive_cmd.append(code)
            else:
                receive_cmd = cmd + ["--yes", "--overwrite", code]

            run(receive_cmd, cwd=tmpdir)

            received_path, install_script = find_install_script(tmpdir)
            if received_path is None:
                print("Error: No files received", flush=True)
                sys.exit(1)

            print(f"Received: {received_path}", flush=True)

            if not install_script.exists():
                print("Error: install.py not found in payload", flush=True)
                sys.exit(1)

            print("Running install.py with uv...", flush=True)
            run(["uv", "run", str(install_script)], cwd=tmpdir)
        finally:
            os.chdir(orig_dir)


def send(transfer, folder_path, code):
    """Send a folder using the chosen code (or let the sender generate one)."""
    folder = Path(folder_path).resolve()
    if not folder.exists() or not folder.is_dir():
        print(
            f"Error: {folder_path} is not a valid directory",
            file=sys.stderr,
            flush=True,
        )
        sys.exit(1)

    install_script = folder / "install.py"
    if not install_script.exists():
        print("Error: install.py not found in folder", file=sys.stderr, flush=True)
        sys.exit(1)

    if transfer == "croc":
        cmd = croc_cmd()
        if cmd is None:
            print(
                "Error: croc is not installed (required for --croc)",
                file=sys.stderr,
                flush=True,
            )
            sys.exit(1)
        send_cmd = cmd + ["send"]
        if code:
            send_cmd += ["--code", code]
        send_cmd.append(str(folder))
        print(f"Sending {folder} ({transfer})...", flush=True)
        run(send_cmd)
        return

    send_cmd = wormhole_cmd() + ["send", ".", "--no-listen"]
    if code:
        send_cmd += ["--code", code]
    print(
        f"Sending {folder_path} ({transfer})"
        + (f" to code {code}" if code else "")
        + "...",
        flush=True,
    )
    run(send_cmd, cwd=str(folder))


def main():
    parser = argparse.ArgumentParser(
        description="Implant - secure payload transfer and execution"
    )
    parser.add_argument("--send", metavar="FOLDER", help="Send folder to receiver")
    parser.add_argument(
        "--code", metavar="CODE", help="Transfer code (sender-generated in reverse mode)"
    )
    parser.add_argument(
        "--receive", action="store_true", help="Receive payload from sender"
    )
    parser.add_argument(
        "--transfer",
        choices=["auto", "wormhole", "croc"],
        default="auto",
        help="Transfer backend (default: auto)",
    )
    parser.add_argument(
        "--wormhole", action="store_true", help="Shortcut for --transfer wormhole"
    )
    parser.add_argument("--croc", action="store_true", help="Shortcut for --transfer croc")

    args = parser.parse_args()

    if args.wormhole and args.croc:
        print("Error: --wormhole and --croc are mutually exclusive", file=sys.stderr)
        sys.exit(1)

    preferred = "wormhole" if args.wormhole else "croc" if args.croc else args.transfer
    transfer = detect_transfer(preferred)
    if transfer is None:
        print(
            "Error: no transfer backend found "
            "(install wormhole or croc, or make uvx available)",
            file=sys.stderr,
            flush=True,
        )
        sys.exit(1)

    if args.send:
        send(transfer, args.send, args.code)
    else:
        receive(transfer, args.code)


if __name__ == "__main__":
    main()
